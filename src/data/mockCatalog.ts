export function resolveAssetUrl(rawSrc?: string): string {
  if (!rawSrc || typeof rawSrc !== 'string') return '';
  const trimmed = rawSrc.trim();
  if (!trimmed) return '';

  // Map any cached or direct /src/assets/images/<file> path to the Vite-bundled asset
  for (const [filename, bundledUrl] of Object.entries(ASSET_FILENAME_MAP)) {
    if (trimmed.includes(filename)) {
      return bundledUrl;
    }
  }

  // Block malformed or Google search/redirect URLs before issuing a network request
  const lower = trimmed.toLowerCase();
  if (
    lower.includes('google.com/url') ||
    lower.includes('google.com/imgres') ||
    lower.includes('google.com/search') ||
    lower.includes('googleusercontent.com/search') ||
    /\s/.test(trimmed)
  ) {
    return '';
  }

  // Allow safe relative/data/blob/http(s) URLs
  if (
    trimmed.startsWith('/') ||
    trimmed.startsWith('data:image/') ||
    trimmed.startsWith('blob:')
  ) {
    return trimmed;
  }

  try {
    const parsed = new URL(trimmed);
    if (parsed.protocol === 'https:' || parsed.protocol === 'http:') {
      return parsed.toString();
    }
  } catch {
    return '';
  }

  return '';
}

